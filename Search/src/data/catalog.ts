import type { CatalogItem } from '../types'

function shoe(partial: Omit<CatalogItem, 'superType' | 'thumbKind' | 'attributes' | 'groups' | 'completenessBars' | 'workflows'> & {
  attributes?: CatalogItem['attributes']
  groups?: CatalogItem['groups']
  completenessBars?: CatalogItem['completenessBars']
  workflows?: CatalogItem['workflows']
}): CatalogItem {
  const sizes = partial.sizes ?? []
  const sizeLabel = sizes.length ? `EU ${sizes[0]}–${sizes[sizes.length - 1]}` : '—'
  const attributes = partial.attributes ?? [
    { label: 'Brand', value: partial.brand ?? '—' },
    { label: 'Color', value: partial.color ?? '—' },
    { label: 'Size run', value: sizeLabel },
    { label: 'Status', value: partial.status },
  ]
  const groups = partial.groups ?? [
    {
      name: 'Identification',
      rows: [
        { label: 'Name', value: partial.name },
        { label: 'SKU', value: partial.sku ?? '—' },
        { label: 'Object type', value: 'Product' },
        { label: 'Brand', value: partial.brand ?? '—' },
      ],
    },
    {
      name: 'Merchandising',
      rows: [
        { label: 'Category', value: partial.category ?? '—' },
        { label: 'Color', value: partial.color ?? '—' },
        { label: 'Color family', value: partial.colorFamily ?? '—' },
        { label: 'Gender', value: partial.gender ?? '—' },
        { label: 'Size run', value: sizes.length ? sizes.map((s) => `EU ${s}`).join(', ') : '—' },
        { label: 'Season', value: partial.season ?? '—' },
        { label: 'List price', value: partial.price ?? '—' },
      ],
    },
    {
      name: 'Physical',
      rows: [
        { label: 'Material', value: partial.material ?? '—' },
        { label: 'Drop', value: partial.id.includes('hoka') ? '5 mm' : '10 mm' },
        { label: 'Weight', value: '265 g (EU 42)' },
      ],
    },
  ]
  const completenessBars = partial.completenessBars ?? [
    { label: 'Product details', value: Math.min(100, partial.completeness + 4) },
    { label: 'Web bullets', value: Math.max(20, partial.completeness - 12) },
    { label: 'Content', value: Math.max(15, partial.completeness - 8) },
  ]
  const workflows = partial.workflows ?? [
    { name: 'Internal review', state: partial.completeness >= 85 ? 'Complete' : 'In progress' },
    { name: 'Channel publish', state: partial.status === 'Approved' ? 'Ready' : 'Blocked' },
  ]
  return {
    ...partial,
    superType: 'product',
    thumbKind: 'shoe',
    attributes,
    groups,
    completenessBars,
    workflows,
  }
}

